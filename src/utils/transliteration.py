_NUKTA_SUBS = [
    ("क\u093c", "क़"), ("ख\u093c", "ख़"), ("ग\u093c", "ग़"),
    ("ज\u093c", "ज़"), ("ड\u093c", "ड़"), ("ढ\u093c", "ढ़"),
    ("फ\u093c", "फ़"),
]


def transliterate_word(word: str) -> str:
    """Transliterate an individual Devanagari word into Urdu script."""
    if not word:
        return ""

    # Normalize composite nuktas (e.g. ड + \u093c -> ड़)
    for src, dst in _NUKTA_SUBS:
        word = word.replace(src, dst)

    # Check high-frequency vocabulary dictionary
    if word in DEV_TO_URDU_VOCAB:
        return DEV_TO_URDU_VOCAB[word]

    # Phonetic character-by-character assembly
    out: list[str] = []
    n = len(word)
    for i, ch in enumerate(word):
        is_last = (i == n - 1)
        if ch in ("े", "ै"):
            out.append("ے" if is_last else "ی")
        elif ch == "ं":
            out.append("ں" if is_last else "ن")
        elif ch in _CHAR_MAP:
            out.append(_CHAR_MAP[ch])
        else:
            out.append(ch)
    return "".join(out)


def devanagari_to_urdu(text: str) -> str:
    """Convert Devanagari Hindi text to Urdu Perso-Arabic script.

    Preserves punctuation, whitespace, and non-Devanagari text (English numbers/words).
    """
    if not text or not re.search(r"[\u0900-\u097F]", text):
        return text

    # Split by word boundaries and whitespace
    tokens = re.split(r"(\s+|[।॥,;?!؟،۔\(\)\[\]\"']+)", text)
    result: list[str] = []

    for token in tokens:
        if not token:
            continue
        if re.search(r"[\u0900-\u097F]", token):
            result.append(transliterate_word(token))
        else:
            # Map punctuation if present
            mapped_punct = token.replace("।", "۔").replace("?", "؟").replace(",", "،").replace(";", "؛")
            result.append(mapped_punct)

    return "".join(result)
